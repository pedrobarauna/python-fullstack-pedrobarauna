# ERRO 1: A função print estava com 'P' maiúsculo (Print). O Python diferencia maiúsculas de minúsculas.
# CORREÇÃO: Alterado para 'print' minúsculo.
print("Bem-vindo ao curso de Python")

# ERRO 2: A string "Carlos" estava sem as aspas de fechamento, gerando um erro de sintaxe.
# CORREÇÃO: Adicionadas as aspas no final.
nome = "Carlos"

# A concatenação estava correta, mas precisava estar em uma nova linha.
print("Aluno: " + nome)

# ERRO 3: O texto dentro do print não estava entre aspas, fazendo o Python achar que eram variáveis.
# CORREÇÃO: Texto colocado entre aspas para ser reconhecido como string.
print("Curso de Python")